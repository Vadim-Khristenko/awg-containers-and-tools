//! Turning one parameter set into a server config, a UAPI request and a client
//! `.conf`.
//!
//! The single most important property in this file is that all three come from
//! the *same* [`Tunnel`] value. AmneziaWG obfuscation is symmetric: the junk
//! packet counts, the magic headers, the padding range and the 3.0 header key
//! have to be byte-identical on both ends. When they are not, nothing reports an
//! error — the peers simply never recognise each other's packets and the
//! handshake times out. So there is one generator, two renderers, and a test
//! that reads both renderings back and compares them field by field.

use base64::{Engine as _, engine::general_purpose::STANDARD as B64};

use crate::awg3::{Awg3Options, Awg3Params, clamp_s_for_header_protection};
use crate::render::{awg3_conf_lines, awg3_uapi_lines};
use crate::rng::Rng;
use crate::{Error, Result};

/// Written into the server config in place of the private key, so the config
/// can be built (and tested) on this machine and completed on the target from a
/// key file that never leaves it.
pub const SERVER_KEY_PLACEHOLDER: &str = "__SERVER_PRIVATE_KEY__";

/// `MessageInitiationSize` and `MessageResponseSize` — `device/noise-protocol.go`.
/// They appear here only because of the S1/S2 collision rule below.
const MESSAGE_INITIATION_SIZE: u32 = 148;
const MESSAGE_RESPONSE_SIZE: u32 = 92;

/// S4 pads transport packets, and the protocol caps it at 32 bytes — every
/// client in `crate::versions::CLIENTS` refuses more, and so does the upstream
/// generator. S1–S3 have no such ceiling.
pub const MAX_S4: u32 = 32;

// ------------------------------------------------------------ 2.0 obfuscation

/// The pre-3.0 obfuscation knobs.
///
/// These are not generated by [`crate::awg3`], which owns the 3.0 block only —
/// but a 3.0 config that omits them is a 3.0 config with a stock WireGuard
/// handshake in front of it, which is exactly the thing DPI matches on. So they
/// are generated here, alongside the deployment that needs them.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BaseObfuscation {
    /// Junk packets sent before the handshake, and their size bounds.
    pub jc: u32,
    pub jmin: u32,
    pub jmax: u32,
    /// Junk prepended to the four handshake message types, S1..S4.
    pub s: [u32; 4],
    /// Magic headers replacing the four WireGuard message type numbers, H1..H4.
    pub h: [u32; 4],
}

impl BaseObfuscation {
    /// `H1..H4` stand in for message types 1..4, so they have to avoid the
    /// values they replace and each other; the daemon demultiplexes on this
    /// number alone and two equal headers make one message type unreachable.
    const H_FLOOR: u32 = 5;
    const H_CEILING: u32 = 2_000_000_000;

    pub fn generate(rng: &mut impl Rng, header_protection: bool) -> Self {
        let jmin = rng.range(20, 60);
        let mut me = Self {
            jc: rng.range(3, 8),
            jmin,
            jmax: jmin + rng.range(30, 120),
            s: [0; 4],
            h: [0; 4],
        };

        for s in &mut me.s {
            // The floor is a floor, not a value: see clamp_s_for_header_protection.
            *s = clamp_s_for_header_protection(rng.range(4, 60), header_protection);
        }
        // The 4..60 draw is right for S1..S3 and out of range for S4, which the
        // protocol caps at MAX_S4.
        me.s[3] = me.s[3].min(MAX_S4);
        // The daemon refuses S1 + 148 == S2 + 92 (device/uapi.go) — an initiation
        // padded to exactly the size of a response would be ambiguous on the wire.
        if me.s[0] + MESSAGE_INITIATION_SIZE == me.s[1] + MESSAGE_RESPONSE_SIZE {
            me.s[1] += 1;
        }

        for i in 0..4 {
            loop {
                let candidate = rng.range(Self::H_FLOOR, Self::H_CEILING);
                if !me.h[..i].contains(&candidate) {
                    me.h[i] = candidate;
                    break;
                }
            }
        }
        me
    }

    /// The invariants a hand-edited or externally supplied set can break.
    pub fn validate(&self) -> Result<()> {
        if self.jmin > self.jmax {
            return Err(Error::Invariant(format!(
                "Jmin ({}) must not exceed Jmax ({})",
                self.jmin, self.jmax
            )));
        }
        for (i, h) in self.h.iter().enumerate() {
            if *h < Self::H_FLOOR {
                return Err(Error::Invariant(format!(
                    "H{} ({h}) collides with a WireGuard message type; it must be >= {}",
                    i + 1,
                    Self::H_FLOOR
                )));
            }
            if self.h[..i].contains(h) {
                return Err(Error::Invariant(format!(
                    "H{} ({h}) repeats an earlier magic header; the peer cannot tell the two message types apart",
                    i + 1
                )));
            }
        }
        if self.s[3] > MAX_S4 {
            return Err(Error::Invariant(format!(
                "S4 ({}) exceeds the protocol maximum of {MAX_S4}",
                self.s[3]
            )));
        }
        if self.s[0] + MESSAGE_INITIATION_SIZE == self.s[1] + MESSAGE_RESPONSE_SIZE {
            return Err(Error::Invariant(format!(
                "S1 ({}) + {MESSAGE_INITIATION_SIZE} must not equal S2 ({}) + {MESSAGE_RESPONSE_SIZE}; the daemon rejects it",
                self.s[0], self.s[1]
            )));
        }
        Ok(())
    }

    /// `.conf` spelling.
    pub fn conf_lines(&self) -> Vec<String> {
        let mut out = vec![
            format!("Jc = {}", self.jc),
            format!("Jmin = {}", self.jmin),
            format!("Jmax = {}", self.jmax),
        ];
        for (i, v) in self.s.iter().enumerate() {
            out.push(format!("S{} = {v}", i + 1));
        }
        for (i, v) in self.h.iter().enumerate() {
            out.push(format!("H{} = {v}", i + 1));
        }
        out
    }

    /// UAPI spelling — same numbers, lowercase keys, `key=value` with no spaces.
    pub fn uapi_lines(&self) -> Vec<String> {
        let mut out = vec![
            format!("jc={}", self.jc),
            format!("jmin={}", self.jmin),
            format!("jmax={}", self.jmax),
        ];
        for (i, v) in self.s.iter().enumerate() {
            out.push(format!("s{}={v}", i + 1));
        }
        for (i, v) in self.h.iter().enumerate() {
            out.push(format!("h{}={v}", i + 1));
        }
        out
    }
}

/// Everything both ends of one tunnel have to agree on.
#[derive(Debug, Clone)]
pub struct Tunnel {
    pub base: BaseObfuscation,
    pub awg3: Awg3Params,
}

impl Tunnel {
    /// Generate one tunnel's worth of obfuscation. Called once per deploy: a
    /// shared parameter set would give every install the same DPI fingerprint.
    pub fn generate(rng: &mut impl Rng, opts: Awg3Options) -> Result<Self> {
        let awg3 = crate::awg3::generate(rng, opts)?;
        let base = BaseObfuscation::generate(rng, opts.header_protection);
        base.validate()?;
        Ok(Self { base, awg3 })
    }

    fn conf_lines(&self) -> Vec<String> {
        let mut out = self.base.conf_lines();
        out.extend(awg3_conf_lines(&self.awg3));
        out
    }

    fn uapi_lines(&self) -> Vec<String> {
        let mut out = self.base.uapi_lines();
        out.extend(awg3_uapi_lines(&self.awg3));
        out
    }
}

