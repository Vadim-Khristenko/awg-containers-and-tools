    #[test]
    fn the_s_floor_applies_only_when_header_protection_is_on() {
        // The floor exists because the header cipher takes its nonce from the
        // padding; with no header key there is no nonce and no floor. Proving
        // the clamp is load-bearing means showing values below it do occur when
        // it is off.
        let below: usize = (0..200u64)
            .map(|seed| BaseObfuscation::generate(&mut SeededRng::new(seed), false))
            .flat_map(|b| b.s.into_iter().collect::<Vec<_>>())
            .filter(|s| *s < 12)
            .count();
        assert!(
            below > 0,
            "the clamp would be untested if S never fell below the floor"
        );

        for seed in 0..200u64 {
            let on = BaseObfuscation::generate(&mut SeededRng::new(seed), true);
            assert!(
                on.s.iter().all(|s| *s >= 12),
                "seed {seed}: S below the nonce floor"
            );
        }
    }

