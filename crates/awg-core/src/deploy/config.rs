    /// `Key = value` out of a `.conf`, restricted to the `[Interface]` block.
    fn interface_block(conf: &str) -> BTreeMap<String, String> {
        let mut out = BTreeMap::new();
        let mut inside = false;
        for line in conf.lines() {
            let line = line.split('#').next().unwrap_or("").trim();
            if line.starts_with('[') {
                inside = line.eq_ignore_ascii_case("[Interface]");
                continue;
            }
            if !inside || line.is_empty() {
                continue;
            }
            if let Some((k, v)) = line.split_once('=') {
                out.insert(k.trim().to_string(), v.trim().to_string());
            }
        }
        out
    }

    /// `key=value` out of a UAPI request, up to the first peer.
    fn uapi_device_block(req: &str) -> BTreeMap<String, String> {
        let mut out = BTreeMap::new();
        for line in req.lines() {
            if line.starts_with("public_key=") {
                break;
            }
            if let Some((k, v)) = line.split_once('=') {
                out.insert(k.to_string(), v.to_string());
            }
        }
        out
    }

