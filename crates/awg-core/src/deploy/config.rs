#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ContainerSpec {
    pub image: String,
    pub name: String,
    /// Host directory bind-mounted at [`Self::CONF_MOUNT`].
    pub conf_dir: String,
    pub restart: String,
}

impl ContainerSpec {
    pub const CONF_MOUNT: &'static str = "/etc/amnezia/awg3";
    pub const CONF_NAME: &'static str = "server.conf";

    pub fn conf_path(&self) -> String {
        format!(
            "{}/{}",
            self.conf_dir.trim_end_matches('/'),
            Self::CONF_NAME
        )
    }
}

impl Default for ContainerSpec {
    fn default() -> Self {
        Self {
            // A published name, not a local one. `awg3-server:latest` only
            // exists on a machine that built it, and it also defeats the
            // detection in `crate::docker`, which recognises our containers by
            // image reference before falling back to a label.
            image: "vaiprog/amnezia-wg-3:latest".into(),
            name: "awg3-server".into(),
            conf_dir: "/etc/amnezia/awg3".into(),
            restart: "unless-stopped".into(),
        }
    }
}

/// The `docker run` that starts the server.
///
/// `NET_ADMIN` plus `/dev/net/tun` and nothing else: amneziawg-go is a userspace
/// implementation, so it needs to create a TUN device and write firewall rules,
/// but it has no business with `--privileged` or the host network namespace. The
/// port is published rather than shared, which keeps the container's own
/// iptables rules out of the host's tables.
pub fn docker_run_command(spec: &ContainerSpec, net: &NetworkSpec) -> String {
    let mut a: Vec<String> = vec![
        "docker run -d".into(),
        format!("--name {}", spec.name),
        format!("--restart {}", spec.restart),
        "--cap-add NET_ADMIN".into(),
        "--device /dev/net/tun".into(),
        "--sysctl net.ipv4.ip_forward=1".into(),
        format!("-p {}:{}/udp", net.listen_port, net.listen_port),
        format!(
            "-v {}:{}:ro",
            spec.conf_dir.trim_end_matches('/'),
            ContainerSpec::CONF_MOUNT
        ),
        // Peer records and the boot counter. Without these the container is
        // stateless in the worst way: recreating it silently revokes every peer
        // `awg-peer` ever issued, and the only symptom is clients that quietly
        // stop handshaking.
        format!("-v {}-state:/var/lib/awg", spec.name),
        format!("-v {}-log:/var/log/awg", spec.name),
        format!("-e AWG_IFACE={}", net.interface),
        format!(
            "-e AWG_CONF={}/{}",
            ContainerSpec::CONF_MOUNT,
            ContainerSpec::CONF_NAME
        ),
        // Without this, configs issued by `awg-peer` inside the container carry
        // a literal SERVER_PUBLIC_IP placeholder as their endpoint. The deploy
        // already knows the real address, so there is no reason to make the
        // operator paste it in afterwards.
        format!("-e AWG_ENDPOINT={}", net.endpoint()),
    ];
    a.push(spec.image.clone());
    a.join(" ")
}

/// Remove any previous container of the same name. `|| true` because "not
/// there" is the expected case on a first deploy, not a failure.
pub fn docker_reset_command(spec: &ContainerSpec) -> String {
    format!("docker rm -f {} >/dev/null 2>&1 || true", spec.name)
}

pub fn docker_logs_command(spec: &ContainerSpec) -> String {
    format!("docker logs --tail 50 {}", spec.name)
}

/// Ask the container's own namespace whether the interface exists and is up.
pub fn interface_check_command(spec: &ContainerSpec, net: &NetworkSpec) -> String {
    format!(
        "docker exec {} ip -o link show {}",
        spec.name, net.interface
    )
}

/// Did the interface actually come up?
///
/// A WireGuard device sits at `state UNKNOWN` forever — it has no carrier to
/// report — so the only meaningful signal is the `UP` flag, and it has to be
/// matched as a whole word: `LOWER_UP` contains it as a substring.
pub fn parse_interface_up(output: &str, interface: &str) -> bool {
    output.lines().any(|line| {
        let Some((head, rest)) = line.split_once('<') else {
            return false;
        };
        if !head
            .split_whitespace()
            .any(|t| t.trim_end_matches(':') == interface)
        {
            return false;
        }
        let Some((flags, _)) = rest.split_once('>') else {
            return false;
        };
        flags.split(',').any(|f| f == "UP")
    })
}

